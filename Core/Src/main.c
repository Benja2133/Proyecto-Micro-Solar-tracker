void MoverServo(uint32_t pos){
	if (pos>PWM_MAX_PULSE) pos = PWM_MAX_PULSE;
	if (pos < PWM_MIN_PULSE) pos = PWM_MIN_PULSE;

	if(!(current==pos)){
		current = pos;
		__HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, pos);
	}
}

